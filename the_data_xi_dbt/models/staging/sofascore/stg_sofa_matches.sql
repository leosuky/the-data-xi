/* trivial tier (flat): passthrough + typed casts.
   NB timestamps are ISO strings ('2025-08-16T14:00:00'), NOT unix epochs. */
select
    {{ passthrough_columns(source('raw','sofa_matches'), 's',
         exclude=['id','ingested_at',
                  'homescore_current','homescore_display','homescore_period1',
                  'homescore_period2','homescore_normaltime',
                  'awayscore_current','awayscore_display','awayscore_period1',
                  'awayscore_period2','awayscore_normaltime',
                  'time_injurytime1','time_injurytime2','homeredcards',
                  'motm_rating','starttimestamp','time_currentperiodstarttimestamp',
                  'time_period1starttimestamp','time_period2starttimestamp']) }},
    nullif(s.homescore_current, '')::int      as homescore_current,
    nullif(s.homescore_display, '')::int      as homescore_display,
    nullif(s.homescore_period1, '')::int      as homescore_period1,
    nullif(s.homescore_period2, '')::int      as homescore_period2,
    nullif(s.homescore_normaltime, '')::int   as homescore_normaltime,
    nullif(s.awayscore_current, '')::int      as awayscore_current,
    nullif(s.awayscore_display, '')::int      as awayscore_display,
    nullif(s.awayscore_period1, '')::int      as awayscore_period1,
    nullif(s.awayscore_period2, '')::int      as awayscore_period2,
    nullif(s.awayscore_normaltime, '')::int   as awayscore_normaltime,
    nullif(s.time_injurytime1, '')::int       as time_injurytime1,
    nullif(s.time_injurytime2, '')::int       as time_injurytime2,
    nullif(s.homeredcards, '')::int           as homeredcards,
    nullif(s.motm_rating, '')::numeric        as motm_rating,
    nullif(s.starttimestamp, '')::timestamp                    as starttimestamp,
    nullif(s.time_currentperiodstarttimestamp, '')::timestamp  as time_currentperiodstarttimestamp,
    nullif(s.time_period1starttimestamp, '')::timestamp        as time_period1starttimestamp,
    nullif(s.time_period2starttimestamp, '')::timestamp        as time_period2starttimestamp
from {{ source('raw','sofa_matches') }} s
